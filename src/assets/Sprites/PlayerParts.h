// Texturas no Renderer andam em ordem head/torso/ARMS/legs/feet, mas
// Parts[] em head/torso/LEGS/feet/arms (7a125e1 inseriu arms no meio
// das texturas sem remapear): índice da PARTE p/ índice da TEXTURA.
// Origem e skip de botas DEVEM usar isto, nunca o índice cru.
inline int partIndexForTex(int texIdx) {
    constexpr int kMap[5] = {0, 1, 4, 2, 3};
    return (texIdx >= 0 && texIdx < 5) ? kMap[texIdx] : 0;
}

inline constexpr int kPlayerPoseCount = 12;

// Seletor aéreo (E): nullptr p/ poses sem variante (chão/direcional
// seguem posePartsFor). Renderer e BodySystem leem daqui quando
// airborne — mesma fonte p/ desenho e hitbox (doutrina B.4).
inline const assets::Part* posePartsForAir(PlayerPose p) {
    switch (p) {
        case PlayerPose::Punch:     return kPlayerPunchAirParts;
        case PlayerPose::PunchUp:   return kPlayerPunchUpAirParts;
        case PlayerPose::PunchDown: return kPlayerPunchDownAirParts;
        case PlayerPose::Throw:     return kPlayerThrowAirParts;
        default:                    return nullptr;
    }
}

